"""Build a single self-contained script for `colab run` (which ships one file): embeds the given
modules verbatim as in-memory modules, then appends the driver script.

  python make_bundle.py OUT.py DRIVER.py MODULE.py [MODULE.py ...]
"""
import sys, os

out, driver, mods = sys.argv[1], sys.argv[2], sys.argv[3:]
here = os.path.dirname(os.path.abspath(__file__))
parts = ["# AUTO-GENERATED by make_bundle.py -- do not edit; edit the sources instead.\n",
         "import sys, types\n",
         "def _install(name, src):\n",
         "    m = types.ModuleType(name); m.__file__ = name + '.py'\n",
         "    sys.modules[name] = m; exec(compile(src, name + '.py', 'exec'), m.__dict__)\n"]
for mpath in mods:
    name = os.path.splitext(os.path.basename(mpath))[0]
    src = open(os.path.join(here, mpath), encoding="utf-8").read()
    parts.append(f"_install({name!r}, {src!r})\n")
drv = open(os.path.join(here, driver), encoding="utf-8").read()
drv = drv.replace("sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))\n", "")
parts.append(drv)
open(os.path.join(here, out), "w", encoding="utf-8").write("".join(parts))
print("wrote", out)
